'use client';
import { useState } from 'react';
import { Button, Field, Input } from '@/components/ui';
import { adminApi } from '@/lib/api';
import { useAdminAuth } from '@/lib/auth';
import { Section, useAction } from '@/features/ui';

type Kind = 'users' | 'clubs' | 'payments' | 'activity';

const REPORTS: { kind: Kind; title: string; description: string; permission: string }[] = [
  {
    kind: 'users',
    title: 'New users',
    description: 'Sign-ups in the period with status, verification and active club count. No email addresses or locations.',
    permission: 'users.view',
  },
  { kind: 'clubs', title: 'Clubs', description: 'Clubs created in the period with status, visibility, category, location and members.', permission: 'clubs.view' },
  { kind: 'payments', title: 'Payments', description: 'All payments with purpose, amount, provider, status, receipt and invoice number.', permission: 'billing.view' },
  {
    kind: 'activity',
    title: 'Daily activity',
    description: 'Validated activities, distance, active members and flagged activities per day.',
    permission: 'platform.overview.view',
  },
];

const iso = (d: Date) => d.toISOString().slice(0, 10);

function download(name: string, text: string) {
  const url = URL.createObjectURL(new Blob([text], { type: 'text/csv;charset=utf-8' }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}

/** CSV exports generated by the API (formula-injection safe). Each download is recorded in the audit log. */
export default function ReportsAdmin() {
  const { can } = useAdminAuth();
  const [from, setFrom] = useState(() => iso(new Date(Date.now() - 30 * 86_400_000)));
  const [to, setTo] = useState(() => iso(new Date()));
  const [busyKind, setBusyKind] = useState<Kind | null>(null);
  const { run, ErrorBox } = useAction();

  const get = (kind: Kind) =>
    run(async () => {
      setBusyKind(kind);
      try {
        const csv = await adminApi.exports.csv(kind, { from: new Date(from).toISOString(), to: new Date(`${to}T23:59:59.999Z`).toISOString() });
        download(`walktogether-${kind}-${from}-to-${to}.csv`, csv);
      } finally {
        setBusyKind(null);
      }
    });

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold">Reports</h1>
        <p className="text-sm text-muted-foreground">Downloadable CSV reports. Moderation cases are under Moderation.</p>
      </div>
      <ErrorBox />
      <div className="flex flex-wrap gap-4">
        <Field id="from" label="From">
          <Input id="from" type="date" value={from} max={to} onChange={(e) => setFrom(e.target.value)} />
        </Field>
        <Field id="to" label="To">
          <Input id="to" type="date" value={to} min={from} onChange={(e) => setTo(e.target.value)} />
        </Field>
      </div>
      <div className="grid gap-4 md:grid-cols-2">
        {REPORTS.filter((r) => can(r.permission)).map((r) => (
          <Section
            key={r.kind}
            title={r.title}
            action={
              <Button size="sm" onClick={() => void get(r.kind)} disabled={busyKind === r.kind}>
                {busyKind === r.kind ? 'Preparing…' : 'Download CSV'}
              </Button>
            }
          >
            <p className="text-sm text-muted-foreground">{r.description}</p>
          </Section>
        ))}
      </div>
    </div>
  );
}
